package by.algotsk;

public class SwapTwoVariablesInOneLine {

    //Допустим, изначально a = 5, b = 10.
    //
    //Берётся текущее значение a → 5.
    //Берётся текущее значение b → 10.
    //Вычисляется подвыражение (b = a):
    //Присваивается b = a → теперь b = 5.
    //Само выражение (b = a) возвращает значение, которое было присвоено, то есть 5. Это важная особенность Java: присваивание — это выражение, возвращающее значение.
    //Теперь выражение выглядит как: a = 5 ^ 10 ^ 5.
    //Считаем: 5 ^ 10 = 15, затем 15 ^ 5 = 10.
    //Присваиваем a = 10.
    //Итог: a = 10, b = 5 — значения поменялись местами.

    static void main() {
        int a = 2, b = 3;

        a = a ^ b ^ ( b = a );
        System.out.printf("A = %d - B = %d%n", a, b);
    }
}
